/** 격자 → 가로 줄 단위 사각형 path (칸 경계에 정확히 맞는다) */
const cache = {};
function pathOf(name) {
  if (cache[name]) return cache[name];
  const rows = GRIDS[name] || GRIDS.logo;
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      let w = 1;
      while (row[x + w] === '#') w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return (cache[name] = d);
}

export function icon(name, size = 16) {
  const s = Math.max(16, Math.round(size / 16) * 16);   // 16·32px 로 맞춤
  return `<svg class="ico" width="${s}" height="${s}" viewBox="0 0 16 16" fill="currentColor"
    shape-rendering="crispEdges" aria-hidden="true"><path d="${pathOf(name)}"/></svg>`;
}
